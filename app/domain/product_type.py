def _normalize(text: str) -> str:
    return re.sub(r"[\s\-_·,/]", "", text.lower())


def find_model(title: str, brand: str | None = None) -> str | None:
    """
    제목에서 모델명을 찾는다. 없으면 None.

    brand를 주면 그 브랜드의 모델만 본다. 브랜드별로 같은 단어가 다른 뜻일 수
    있기 때문이다 — 샤넬의 "19"는 모델명이지만 다른 브랜드에서는 크기나 연도다.

    가장 긴 이름부터 확인한다. "19백"과 "19"가 모두 사전에 있을 때 짧은 쪽이
    먼저 걸리면 안 되기 때문이다.
    """
    normalized = _normalize(title)
    candidates = BAG_MODELS.get(brand, ()) if brand else _ALL_MODELS

    for model in sorted(candidates, key=len, reverse=True):
        if _normalize(model) in normalized:
            return MODEL_CANONICAL.get(model, model)

    return None


def classify_category(
    title: str, brand: str | None = None
) -> tuple[str | None, str | None]:
    """
    카테고리를 판정한다. (카테고리, 걸린 키워드)를 반환한다.

    - 5종 중 하나면 ("bag" 등, None 또는 판정 키워드)
    - 수집 대상이 아니면 (None, 제외를 일으킨 키워드)

    판정 순서가 중요하다 (기존 is_bag의 순서를 계승한다):

    1. 부속품 — "가방 스트랩"은 가방 단어가 있어도 부속품이다.
    2. 비품목 — 향수·쇼핑백·잡화. 5종 어디에도 안 들어간다.
    3. 가방 모델명 — 사전에 있으면 가방 확정. "샤넬 뉴미니"처럼 카테고리
       단어가 아예 없는 제목을 살린다. 모델명이 지갑 규칙보다 먼저인 것도
       기존 순서 그대로다.
    4. 지갑 — 가방 단어가 함께 없으면 제외 (수집 카테고리에 지갑은 없다).
    5. 최전방 키워드 — 가방·시계·주얼리·의류·신발 어휘 중 제목에서 가장
       앞에 나온 것이 이긴다. 상품명이 앞에 오고 부연이 뒤에 붙는다는,
       detect_brand와 같은 근거다.
    """
    text = title.lower()

    for keyword in ACCESSORY_KEYWORDS:
        if keyword in text:
            return None, keyword

    for keyword in NON_ITEM_KEYWORDS:
        if keyword in text:
            return None, keyword

    # 지갑 단어는 경쟁 전에 가려둔다. "반지갑"의 "반지"가 주얼리로 잡히는
    # 오탐이 실제로 난다 — 지갑 여부는 맨 뒤에서 따로 판정한다.
    masked = text
    for keyword in WALLET_KEYWORDS:
        masked = masked.replace(keyword, " ")

    # 최전방 키워드 경쟁. 상품명이 앞에 오고 부연이 뒤에 붙는다는,
    # detect_brand와 같은 근거(실측 92건에서 예외 없음)를 쓴다.
    lexicon: dict[str, tuple[str, ...]] = {"bag": BAG_WORDS, **CATEGORY_KEYWORDS}
    best_position = len(masked) + 1
    best: tuple[str | None, str | None] = (None, None)

    for category, keywords in lexicon.items():
        for keyword in keywords:
            position = masked.find(keyword)

            if 0 <= position < best_position:
                best_position = position
                best = (category, keyword)

    if best[0] is not None:
        return best

    # 카테고리 단어가 하나도 없을 때만 모델 사전을 본다. "샤넬 뉴미니"처럼
    # 단어 없이 모델명만 쓰는 제목을 살리되, "구찌 인터로킹 목걸이"처럼
    # 명시적 카테고리 단어가 있으면 그쪽이 이긴다 — 같은 이름이 가방과
    # 주얼리 라인에 함께 있는 브랜드가 실제로 있다.
    if find_model(title, brand):
        return "bag", None

    for keyword in WALLET_KEYWORDS:
        if keyword in text:
            return None, keyword

    return None, None


def is_bag(title: str, brand: str | None = None) -> tuple[bool, str | None]:
    """
    가방인지 판정한다. (판정, 제외 사유)를 반환하고, 가방이면 사유는 None.

    classify_category의 얇은 래퍼로 남겨둔 이유: 가방 판정을 직접 묻는 기존
    호출처(테스트 포함)가 많고, "걸린 키워드"를 사유로 돌려주는 계약이 진단
    로그에 이미 박혀 있어서다.
    """
    category, detail = classify_category(title, brand)

    if category == "bag":
        return True, None

    return False, detail
